"""Generates source/utf_case_table.cc with Unicode simple case mappings.

Input is UnicodeData.txt from the Unicode Character Database, fields 12 (simple uppercase mapping)
and 13 (simple lowercase mapping). Output tables are sorted by code point for binary search.

usage: gen_utf_case_table.py <UnicodeData.txt> <unicode version> <output .cc>
"""
import sys


def read_mappings(path):
  lower = []
  upper = []
  with open(path, encoding='utf-8') as data:
    for line in data:
      fields = line.rstrip('\n').split(';')
      if len(fields) < 15:
        continue
      code = int(fields[0], 16)
      if fields[12]:
        upper.append((code, int(fields[12], 16)))
      if fields[13]:
        lower.append((code, int(fields[13], 16)))
  lower.sort()
  upper.sort()
  return lower, upper


def emit_table(out, name, pairs):
  out.write(f'static constexpr std::array<case_pair_t, {len(pairs)}> {name}_data{{{{\n')
  for code, mapped in pairs:
    out.write(f'  case_pair_t{{0x{code:04X}, 0x{mapped:04X}}},\n')
  out.write('}};\n\n')


def main():
  if len(sys.argv) != 4:
    sys.exit(__doc__)
  source, version, output = sys.argv[1:]
  lower, upper = read_mappings(source)
  with open(output, 'w', encoding='utf-8', newline='\n') as out:
    out.write(
      '// SPDX-FileCopyrightText: 2026 Artur Bać\n'
      '// SPDX-License-Identifier: BSL-1.0 AND Unicode-3.0\n'
      '// SPDX-PackageHomePage: https://github.com/arturbac/stralgo\n'
      '//\n'
      f'// Generated by tools/gen_utf_case_table.py from UnicodeData.txt, Unicode {version}.\n'
      '// Data derived from the Unicode Character Database, see LICENSE-UNICODE.\n'
      '// Generated file: changes come only from regeneration.\n'
      '// clang-format off\n'
      '#include "utf_case_table.h"\n\n'
      'namespace stralgo::inline v1_4::utf::detail\n'
      '  {\n'
    )
    emit_table(out, 'lower_case_pairs', lower)
    emit_table(out, 'upper_case_pairs', upper)
    out.write(
      'std::span<case_pair_t const> const lower_case_pairs{lower_case_pairs_data};\n'
      'std::span<case_pair_t const> const upper_case_pairs{upper_case_pairs_data};\n'
      '  }  // namespace stralgo::utf::detail\n'
      '// clang-format on\n'
    )
  print(f'lower {len(lower)} upper {len(upper)}')


if __name__ == '__main__':
  main()
